// 체중 구간 사이를 선형보간해 절대 기준 1RM(kg) 계산
const interpolateStandardKg = (
  bodyweight: number,
  table: BracketTable,
): number => {
  if (!table.length) return 0;

  const first = table[0];
  const last = table[table.length - 1];

  if (bodyweight <= first[0]) return first[1];
  if (bodyweight >= last[0]) return last[1];

  for (let i = 0; i < table.length - 1; i += 1) {
    const [bw1, v1] = table[i];
    const [bw2, v2] = table[i + 1];
    if (bodyweight >= bw1 && bodyweight <= bw2) {
      const t = (bodyweight - bw1) / (bw2 - bw1);
      return v1 + t * (v2 - v1);
    }
  }

  return last[1];
};

export const getAgeBracket = (age: number): AgeBracket => {
  if (age < 40) return '18-39';
  if (age < 50) return '40-49';
  if (age < 60) return '50-59';
  return '60+';
};

// 체중/성별/연령대/종목에 맞는 기준 1RM(kg)을 반환
export const getStandardKg = (
  gender: Gender,
  subject: LiftSubject,
  ageBracket: AgeBracket,
  bodyweight: number,
): number => {
  const table = STANDARDS_BY_AGE_KG[ageBracket][gender][subject];
  const calculatedKg = interpolateStandardKg(bodyweight, table);

  return Math.round(calculatedKg * 10) / 10;
};

// 안내 툴팁 등에서 참고용으로 보여줄 때 쓰는 헬퍼 함수
export const getReferenceBodyweight = (gender: Gender): number =>
  REFERENCE_BODYWEIGHT[gender];
